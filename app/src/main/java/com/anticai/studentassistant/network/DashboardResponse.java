package com.anticai.studentassistant.network;

public class DashboardResponse {

    private Long id;
    private String name;
    private String email;
    private String role;

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getRole() {
        return role;
    }
}